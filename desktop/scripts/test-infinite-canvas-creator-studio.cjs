const fs=require("fs");
const path=require("path");
const file=path.resolve(__dirname,"../src/renderer/infinite-canvas.js");
const css=path.resolve(__dirname,"../src/renderer/styles/infinite-canvas.css");
const source=fs.readFileSync(file,"utf8");
const styles=fs.readFileSync(css,"utf8");
const results=[];
const check=(name,passed,detail="")=>results.push({name,passed:Boolean(passed),detail:passed?"":detail});
check("空白画布显示统一品牌文案",source.includes('class="lfc-empty-hero lfc-empty-canvas"')&&source.includes("灵感，即刻成帧"));
check("空白画布只显示右键创建提示",source.includes("右击画布空白处创建节点")&&!source.includes('data-lfc-empty-form>'));
check("空白提示层不拦截画布交互",styles.includes(".lfc-empty-canvas{width:auto;max-width:none;pointer-events:none"));
check("右键菜单仍提供节点创建入口",source.includes("function renderMenus")&&source.includes('data-menu-kind'));
check("创作台生成和资源能力保留为兼容逻辑",source.includes("startCreatorGeneration")&&source.includes("renderCreatorAssetPicker")&&source.includes("pickAssetsForCurrentProject"));
check("首屏不再挂载创作台渲染函数",!source.includes("bindGroups(stage); bindNodes(stage); bindEdges(stage); renderCreatorStudio(stage);")&&source.includes("bindGroups(stage); bindNodes(stage); bindEdges(stage);"));
check("沉浸模式工具栏避开左侧资源栏",styles.includes(".lfc-stage.immersive .lfc-main{box-sizing:border-box;padding-left:244px}"));
check("全屏保留左侧收起按钮",source.includes("data-lfc-toggle-left")&&styles.includes(".lfc-stage.immersive .lfc-library-head button{display:grid"));
const failed=results.filter(item=>!item.passed);
const output={test:"infinite-canvas-creator-studio",total:results.length,passed:results.length-failed.length,failed:failed.length,results};
console.log(JSON.stringify(output,null,2));
process.exitCode=failed.length?1:0;
